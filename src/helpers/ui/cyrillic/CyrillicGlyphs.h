inline uint8_t advanceFor(const CyrBitmapFont& font, int idx) {
  if (idx < 0 || idx >= 66) return 0;
  return pgm_read_byte(font.advance + idx);
}

inline bool pixelFor(const CyrBitmapFont& font, int idx, int x, int y) {
  if (idx < 0 || idx >= 66) return false;
  const uint8_t w = advanceFor(font, idx);
  if ((unsigned)x >= w || (unsigned)y >= font.height) return false;
  const uint16_t off = pgm_read_word(font.offset + idx);
  const uint8_t rowb = (uint8_t)((w + 7) >> 3);
  const uint8_t b =
      pgm_read_byte(font.bits + off + (uint16_t)y * rowb + (x >> 3));
  return (b & (uint8_t)(0x80 >> (x & 7))) != 0;
}
