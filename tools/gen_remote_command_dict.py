#!/usr/bin/env python3
"""Generate RemoteCommandDictionary.h from the ed25519-signer dictionary.

The firmware must use exactly the same token order and the same dict_id as the
signer. Run this script whenever tools/remote_command_dictionary.txt changes:

    python3 tools/gen_remote_command_dict.py

The generated header is committed so the firmware build does not need Python.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

MAX_TOKENS = 254
ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / "tools" / "remote_command_dictionary.txt"
DEFAULT_OUTPUT = ROOT / "examples" / "simple_repeater" / "RemoteCommandDictionary.h"


def unescape(line: str) -> bytes:
    out = bytearray()
    i = 0
    while i < len(line):
        ch = line[i]
        if ch != "\\":
            out.extend(ch.encode("utf-8"))
            i += 1
            continue
        i += 1
        if i >= len(line):
            raise ValueError("trailing backslash in dictionary")
        esc = line[i]
        if esc == "s":
            out.append(32)
        elif esc == "t":
            out.append(9)
        elif esc == "n":
            out.append(10)
        elif esc == "r":
            out.append(13)
        elif esc == "\\":
            out.append(92)
        elif esc == "x":
            if i + 2 >= len(line):
                raise ValueError("bad \\x escape in dictionary")
            out.append(int(line[i + 1 : i + 3], 16))
            i += 2
        else:
            raise ValueError(f"unknown dictionary escape \\{esc}")
        i += 1
    return bytes(out)


def c_escape(data: bytes) -> str:
    parts = []
    for byte in data:
        if byte == 0x22:
            parts.append('\\"')
        elif byte == 0x5C:
            parts.append("\\\\")
        elif 0x20 <= byte <= 0x7E:
            parts.append(chr(byte))
        elif byte == 0x0A:
            parts.append("\\n")
        elif byte == 0x0D:
            parts.append("\\r")
        elif byte == 0x09:
            parts.append("\\t")
        else:
            # Three-digit octal: unlike \x, it cannot absorb the first
            # character of the next token (e.g. "10" or "clkreboot").
            parts.append(f"\\{byte:03o}")
    return "".join(parts)


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
    dst = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUTPUT

    raw = src.read_bytes()
    lines = [line for line in raw.decode("utf-8").splitlines() if line]
    tokens = [unescape(line) for line in lines]

    if not tokens:
        raise SystemExit("dictionary is empty")
    if len(tokens) > MAX_TOKENS:
        raise SystemExit(f"too many tokens: {len(tokens)} (max {MAX_TOKENS})")
    if len(set(tokens)) != len(tokens):
        raise SystemExit("dictionary contains duplicate tokens")
    for token in tokens:
        if not token:
            raise SystemExit("dictionary contains an empty token")
        if b"\x00" in token:
            raise SystemExit("dictionary token contains NUL")

    blob = b"\x00".join(tokens) + b"\x00"
    offsets = []
    pos = 0
    for token in tokens:
        offsets.append(pos)
        pos += len(token) + 1

    dict_id = int.from_bytes(hashlib.sha256(b"\x00".join(tokens)).digest()[:2], "little")
    source_sha = hashlib.sha256(raw).hexdigest()

    out = []
    out.append("// Generated by tools/gen_remote_command_dict.py. Do not edit by hand.")
    out.append("// Source: https://github.com/alexxxst/ed25519-signer/blob/main/dictionary.txt")
    out.append(f"// Source SHA-256: {source_sha}")
    out.append("")
    out.append("#pragma once")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append(f"#define REMOTE_CMD_DICT_ID        0x{dict_id:04X}u")
    out.append(f"#define REMOTE_CMD_DICT_COUNT     {len(tokens)}u")
    out.append("")
    out.append("static const char REMOTE_CMD_DICT_BLOB[] =")
    out.append(f'  "{c_escape(blob)}";')
    out.append("")
    out.append(f"static const uint16_t REMOTE_CMD_DICT_OFFSETS[REMOTE_CMD_DICT_COUNT] = {{")
    for i in range(0, len(offsets), 8):
        chunk = ", ".join(str(v) for v in offsets[i : i + 8])
        out.append(f"  {chunk},")
    out.append("};")
    out.append("")
    out.append("static inline const char* remoteCmdDictToken(uint8_t code) {")
    out.append("  if (code >= REMOTE_CMD_DICT_COUNT) return nullptr;")
    out.append("  return &REMOTE_CMD_DICT_BLOB[REMOTE_CMD_DICT_OFFSETS[code]];")
    out.append("}")
    out.append("")
    out.append('static_assert(REMOTE_CMD_DICT_COUNT <= 254, "cmdpack supports at most 254 tokens");')
    out.append("")

    dst.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {dst} ({len(tokens)} tokens, dict_id=0x{dict_id:04X})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
